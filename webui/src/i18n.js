export function t(text) {
  if (language === "vi") return text;
  return EN[text] ?? text;
}

/** Translate `text`, then substitute each `{}` with the next argument. */
export function tf(text, ...values) {
  let index = 0;
  return t(text).replace(/\{\}/g, () => (index < values.length ? String(values[index++]) : "{}"));
}

