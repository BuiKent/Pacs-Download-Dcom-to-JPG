export function translateLog(message) {
  const text = String(message ?? "");
  if (language === "vi") return text;
  if (EN[text]) return EN[text];
  return LOG_PATTERNS.reduce(
    (value, [pattern, replacement]) => value.replace(pattern, replacement),
    text,
  );
}
